const buckets = [
  ["Features", /^(feat|feature)(\(.+\))?:/i],
  ["Fixes", /^(fix|bugfix|hotfix)(\(.+\))?:/i],
  ["Performance", /^(perf|performance)(\(.+\))?:/i],
  ["Maintenance", /^(chore|refactor|build|ci|docs|test)(\(.+\))?:/i]
];

export function parseCommits(raw) {
  return raw.split("\x1e").filter(Boolean).map(row => {
    const [sha, subject] = row.split("\x1f");
    return { sha, subject: subject || "" };
  });
}

export function analyzeHistory(rawCommits, rawStat, meta = {}) {
  const commits = parseCommits(rawCommits);
  const groups = Object.fromEntries(buckets.map(([name]) => [name, []]));
  groups.Other = [];
  for (const commit of commits) {
    const match = buckets.find(([, pattern]) => pattern.test(commit.subject));
    groups[match?.[0] || "Other"].push(commit);
  }
  const files = rawStat.split("\n").filter(Boolean).map(line => {
    const [added, deleted, path] = line.split("\t");
    return { added: Number(added) || 0, deleted: Number(deleted) || 0, path };
  });
  const additions = files.reduce((sum, file) => sum + file.added, 0);
  const deletions = files.reduce((sum, file) => sum + file.deleted, 0);
  const sensitive = files.filter(file => /(auth|security|permission|migration|schema|config|\.env)/i.test(file.path));
  const signals = [];
  if (sensitive.length) signals.push(`Review sensitive paths: ${sensitive.slice(0, 3).map(x => `\`${x.path}\``).join(", ")}.`);
  if (commits.some(c => /breaking|!:|migration/i.test(c.subject))) signals.push("Potential breaking change language appears in commit history.");
  if (files.length > 30) signals.push("Broad file footprint; consider a focused smoke test pass.");
  if (!signals.length) signals.push("No automatic release-risk signals found; validate product behavior before shipping.");
  return { title: meta.title || "Release brief", base: meta.base || "unknown", commits, groups, files, additions, deletions, signals };
}

export function renderMarkdown(report) {
  const lines = [`# ${report.title}`, "", `Compared \`${report.base}\` → \`HEAD\`. Generated by [release-sieve](https://github.com/Chandan-14r/release-sieve).`, "", "## At a glance", "", `- **${report.commits.length}** commits across **${report.files.length}** files`, `- **+${report.additions} / -${report.deletions}** lines`, "", "## What changed", ""];
  for (const [name, commits] of Object.entries(report.groups)) {
    if (!commits.length) continue;
    lines.push(`### ${name}`, "", ...commits.map(c => `- ${c.subject} (${c.sha.slice(0, 7)})`), "");
  }
  lines.push("## Release signals", "", ...report.signals.map(signal => `- ${signal}`), "", "## Suggested ship checklist", "", "- [ ] Run the relevant automated checks", "- [ ] Verify the user-facing happy path", "- [ ] Confirm rollback or mitigation ownership", "");
  return lines.join("\n");
}

export function renderJson(report) {
  return `${JSON.stringify({
    schemaVersion: "1.0",
    generatedBy: "release-sieve",
    title: report.title,
    comparison: { base: report.base, head: "HEAD" },
    summary: {
      commitCount: report.commits.length,
      fileCount: report.files.length,
      additions: report.additions,
      deletions: report.deletions,
      riskSignalCount: report.signals.filter(signal => !signal.startsWith("No automatic")).length
    },
    changes: Object.fromEntries(
      Object.entries(report.groups)
        .filter(([, commits]) => commits.length)
        .map(([name, commits]) => [name.toLowerCase(), commits])
    ),
    files: report.files,
    signals: report.signals
  }, null, 2)}\n`;
}

function escapeHtml(value) {
  return String(value).replace(/[&<>\"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[character]);
}

